-- HyperStack bench: the shop tables in TESTDB (Db2), the same rows as the
-- Postgres bench. seed-db2.sh runs db2-drop.sql first, so this re-runs.
CREATE TABLE customers (
  id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(200) NOT NULL UNIQUE,
  city VARCHAR(100),
  joined DATE NOT NULL DEFAULT CURRENT DATE
);
CREATE TABLE products (
  id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(20) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  in_stock INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE orders (
  id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER REFERENCES customers(id),
  placed TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  status VARCHAR(20) NOT NULL DEFAULT 'new'
);
CREATE TABLE order_lines (
  id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id INTEGER REFERENCES orders(id),
  product_id INTEGER REFERENCES products(id),
  qty INTEGER NOT NULL
);
