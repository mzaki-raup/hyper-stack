WHENEVER SQLERROR EXIT FAILURE
SET FEEDBACK OFF
DROP VIEW IF EXISTS order_totals;
DROP TABLE IF EXISTS order_lines PURGE;
DROP TABLE IF EXISTS orders PURGE;
DROP TABLE IF EXISTS products PURGE;
DROP TABLE IF EXISTS customers PURGE;
CREATE TABLE customers (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR2(100) NOT NULL,
  email VARCHAR2(200) NOT NULL UNIQUE,
  city VARCHAR2(100),
  joined DATE DEFAULT SYSDATE NOT NULL
);
CREATE TABLE products (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR2(20) NOT NULL UNIQUE,
  name VARCHAR2(100) NOT NULL,
  price NUMBER(10,2) NOT NULL,
  in_stock NUMBER DEFAULT 0 NOT NULL
);
CREATE TABLE orders (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER REFERENCES customers(id),
  placed TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  status VARCHAR2(20) DEFAULT 'new' NOT NULL
);
CREATE TABLE order_lines (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id NUMBER REFERENCES orders(id),
  product_id NUMBER REFERENCES products(id),
  qty NUMBER NOT NULL
);
