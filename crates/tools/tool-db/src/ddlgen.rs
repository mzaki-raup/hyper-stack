//! DDL generation from a [`Snapshot`] (docs/10-depth-programme.md phase H).
//!
//! The target dialect is chosen by the caller rather than taken from the
//! snapshot, so a Postgres schema can be written out as MySQL or SQLite.
//! Column types are passed through as the source server spelled them: this
//! module arranges the statements, it does not translate type systems, and
//! the UI says so.
//!
//! Statements come out in three groups - tables, then indexes, then foreign
//! keys - so the script can be run top to bottom whatever order the tables
//! reference each other in. SQLite is the exception: it cannot add a key
//! after the fact, so its keys are written inside the table.

use crate::driver::Engine;
use crate::schema::{ForeignKey, IndexDef, Snapshot, TableSchema};
use crate::sql::quote_ident;

/// What to include. The UI offers each as a checkbox.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Options {
    pub if_not_exists: bool,
    pub indexes: bool,
    pub foreign_keys: bool,
    /// `DROP TABLE` before each `CREATE TABLE`.
    pub drop_first: bool,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            if_not_exists: false,
            indexes: true,
            foreign_keys: true,
            drop_first: false,
        }
    }
}

/// How a table is named in the target dialect: SQLite has no schemas, so
/// the prefix is dropped there.
fn table_ref(schema: &str, name: &str, engine: Engine) -> String {
    if engine == Engine::Sqlite || schema.is_empty() {
        quote_ident(name, engine)
    } else {
        format!(
            "{}.{}",
            quote_ident(schema, engine),
            quote_ident(name, engine)
        )
    }
}

fn column_list(columns: &[String], engine: Engine) -> String {
    columns
        .iter()
        .map(|c| quote_ident(c, engine))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The auto-increment spelling, which differs in both syntax and position.
/// SQLite only accepts `AUTOINCREMENT` on an `INTEGER PRIMARY KEY`, so it is
/// written by [`create_table`] with the key instead of here.
fn auto_increment(engine: Engine) -> &'static str {
    match engine {
        Engine::Mysql => " AUTO_INCREMENT",
        Engine::Postgres => " GENERATED BY DEFAULT AS IDENTITY",
        Engine::Sqlite => "",
    }
}

/// One `CREATE TABLE`, with the primary key and - for SQLite - the foreign
/// keys inline.
pub fn create_table(t: &TableSchema, engine: Engine, opts: &Options) -> String {
    let mut out = String::with_capacity(256);
    if opts.drop_first {
        out.push_str(&format!(
            "DROP TABLE IF EXISTS {};\n",
            table_ref(&t.schema, &t.name, engine)
        ));
    }
    let exists = if opts.if_not_exists {
        "IF NOT EXISTS "
    } else {
        ""
    };
    out.push_str(&format!(
        "CREATE TABLE {exists}{} (\n",
        table_ref(&t.schema, &t.name, engine)
    ));

    // A single-column integer key is written on the column for SQLite, which
    // is the only way to get AUTOINCREMENT and rowid aliasing.
    let sqlite_inline_key = engine == Engine::Sqlite
        && t.primary_key.len() == 1
        && t.column(&t.primary_key[0])
            .is_some_and(|c| c.auto_increment);

    let mut parts: Vec<String> = Vec::with_capacity(t.columns.len() + 2);
    for c in &t.columns {
        let mut line = format!("    {} {}", quote_ident(&c.name, engine), c.data_type);
        if sqlite_inline_key && t.primary_key[0] == c.name {
            line.push_str(" PRIMARY KEY AUTOINCREMENT");
        } else if c.auto_increment {
            line.push_str(auto_increment(engine));
        }
        if !c.nullable {
            line.push_str(" NOT NULL");
        }
        if let Some(d) = &c.default {
            line.push_str(&format!(" DEFAULT {d}"));
        }
        parts.push(line);
    }
    if !t.primary_key.is_empty() && !sqlite_inline_key {
        parts.push(format!(
            "    PRIMARY KEY ({})",
            column_list(&t.primary_key, engine)
        ));
    }
    if engine == Engine::Sqlite && opts.foreign_keys {
        for fk in &t.foreign_keys {
            parts.push(format!("    {}", inline_foreign_key(fk, engine)));
        }
    }

    out.push_str(&parts.join(",\n"));
    out.push_str("\n);");
    out
}

/// `FOREIGN KEY (…) REFERENCES …`, the part both the inline and the
/// `ALTER TABLE` forms share.
fn inline_foreign_key(fk: &ForeignKey, engine: Engine) -> String {
    let mut s = format!(
        "FOREIGN KEY ({}) REFERENCES {} ({})",
        column_list(&fk.columns, engine),
        table_ref(&fk.ref_schema, &fk.ref_table, engine),
        column_list(&fk.ref_columns, engine)
    );
    if let Some(a) = &fk.on_delete {
        s.push_str(&format!(" ON DELETE {a}"));
    }
    if let Some(a) = &fk.on_update {
        s.push_str(&format!(" ON UPDATE {a}"));
    }
    s
}

/// `ALTER TABLE … ADD CONSTRAINT … FOREIGN KEY …`. Empty for SQLite, whose
/// keys [`create_table`] already wrote.
pub fn add_foreign_key(t: &TableSchema, fk: &ForeignKey, engine: Engine) -> Option<String> {
    if engine == Engine::Sqlite {
        return None;
    }
    let name = if fk.name.is_empty() {
        format!("fk_{}_{}", t.name, fk.columns.join("_"))
    } else {
        fk.name.clone()
    };
    Some(format!(
        "ALTER TABLE {} ADD CONSTRAINT {} {};",
        table_ref(&t.schema, &t.name, engine),
        quote_ident(&name, engine),
        inline_foreign_key(fk, engine)
    ))
}

/// `CREATE INDEX` for one index. The primary key's own index is skipped: it
/// comes with the table.
pub fn create_index(t: &TableSchema, ix: &IndexDef, engine: Engine) -> Option<String> {
    if ix.primary {
        return None;
    }
    let unique = if ix.unique { "UNIQUE " } else { "" };
    Some(format!(
        "CREATE {unique}INDEX {} ON {} ({});",
        quote_ident(&ix.name, engine),
        table_ref(&t.schema, &t.name, engine),
        column_list(&ix.columns, engine)
    ))
}

/// The whole script for a snapshot, in dependency-safe order.
pub fn script(snap: &Snapshot, engine: Engine, opts: &Options) -> String {
    let mut out = String::with_capacity(1024);
    for t in &snap.tables {
        out.push_str(&create_table(t, engine, opts));
        out.push_str("\n\n");
    }
    if opts.indexes {
        let mut any = false;
        for t in &snap.tables {
            for ix in &t.indexes {
                if let Some(s) = create_index(t, ix, engine) {
                    out.push_str(&s);
                    out.push('\n');
                    any = true;
                }
            }
        }
        if any {
            out.push('\n');
        }
    }
    if opts.foreign_keys {
        let mut any = false;
        for t in &snap.tables {
            for fk in &t.foreign_keys {
                if let Some(s) = add_foreign_key(t, fk, engine) {
                    out.push_str(&s);
                    out.push('\n');
                    any = true;
                }
            }
        }
        if any {
            out.push('\n');
        }
    }
    while out.ends_with('\n') {
        out.pop();
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::ColumnDef;

    fn col(name: &str, ty: &str, nullable: bool) -> ColumnDef {
        ColumnDef {
            name: name.into(),
            data_type: ty.into(),
            nullable,
            default: None,
            auto_increment: false,
        }
    }

    fn orders() -> TableSchema {
        TableSchema {
            schema: "public".into(),
            name: "orders".into(),
            columns: vec![
                ColumnDef {
                    auto_increment: true,
                    ..col("id", "integer", false)
                },
                col("customer_id", "integer", false),
                col("note", "text", true),
            ],
            primary_key: vec!["id".into()],
            indexes: vec![
                IndexDef {
                    name: "orders_pkey".into(),
                    columns: vec!["id".into()],
                    unique: true,
                    primary: true,
                },
                IndexDef {
                    name: "orders_customer".into(),
                    columns: vec!["customer_id".into()],
                    unique: false,
                    primary: false,
                },
            ],
            foreign_keys: vec![ForeignKey {
                name: "orders_customer_fk".into(),
                columns: vec!["customer_id".into()],
                ref_schema: "public".into(),
                ref_table: "customers".into(),
                ref_columns: vec!["id".into()],
                on_delete: Some("CASCADE".into()),
                on_update: None,
            }],
        }
    }

    #[test]
    fn postgres_writes_identity_and_a_table_level_key() {
        let sql = create_table(&orders(), Engine::Postgres, &Options::default());
        assert!(sql.contains("CREATE TABLE public.orders"), "{sql}");
        assert!(
            sql.contains("id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL"),
            "{sql}"
        );
        assert!(sql.contains("PRIMARY KEY (id)"), "{sql}");
        // Postgres adds its keys afterwards, never inside the table.
        assert!(!sql.contains("FOREIGN KEY"), "{sql}");
    }

    #[test]
    fn mysql_writes_auto_increment_and_backticks() {
        let sql = create_table(&orders(), Engine::Mysql, &Options::default());
        assert!(sql.contains("public.orders"), "{sql}");
        assert!(sql.contains("id integer AUTO_INCREMENT NOT NULL"), "{sql}");
    }

    #[test]
    fn sqlite_inlines_the_key_and_the_foreign_keys() {
        let sql = create_table(&orders(), Engine::Sqlite, &Options::default());
        // No schema prefix: SQLite has none.
        assert!(sql.contains("CREATE TABLE orders"), "{sql}");
        assert!(!sql.contains("public"), "{sql}");
        assert!(
            sql.contains("id integer PRIMARY KEY AUTOINCREMENT"),
            "{sql}"
        );
        // The key is on the column, so there is no table-level one.
        assert!(!sql.contains("PRIMARY KEY (id)"), "{sql}");
        assert!(
            sql.contains("FOREIGN KEY (customer_id) REFERENCES customers (id) ON DELETE CASCADE"),
            "{sql}"
        );
    }

    #[test]
    fn sqlite_has_no_alter_table_add_constraint() {
        let t = orders();
        assert!(add_foreign_key(&t, &t.foreign_keys[0], Engine::Sqlite).is_none());
        let pg = add_foreign_key(&t, &t.foreign_keys[0], Engine::Postgres).unwrap();
        assert!(
            pg.starts_with("ALTER TABLE public.orders ADD CONSTRAINT"),
            "{pg}"
        );
        assert!(pg.contains("ON DELETE CASCADE"), "{pg}");
        assert!(!pg.contains("ON UPDATE"), "{pg}");
    }

    #[test]
    fn the_primary_key_index_is_not_written_again() {
        let t = orders();
        assert!(create_index(&t, &t.indexes[0], Engine::Postgres).is_none());
        let ix = create_index(&t, &t.indexes[1], Engine::Postgres).unwrap();
        assert_eq!(
            ix,
            "CREATE INDEX orders_customer ON public.orders (customer_id);"
        );
    }

    #[test]
    fn a_unique_index_says_so() {
        let mut t = orders();
        t.indexes[1].unique = true;
        let ix = create_index(&t, &t.indexes[1], Engine::Postgres).unwrap();
        assert!(ix.starts_with("CREATE UNIQUE INDEX"), "{ix}");
    }

    #[test]
    fn a_default_and_a_nullable_column_round_trip() {
        let t = TableSchema {
            name: "t".into(),
            columns: vec![ColumnDef {
                default: Some("now()".into()),
                ..col("created", "timestamptz", true)
            }],
            ..Default::default()
        };
        let sql = create_table(&t, Engine::Postgres, &Options::default());
        assert!(sql.contains("created timestamptz DEFAULT now()"), "{sql}");
        assert!(!sql.contains("NOT NULL"), "{sql}");
    }

    #[test]
    fn options_add_drop_and_if_not_exists() {
        let opts = Options {
            if_not_exists: true,
            drop_first: true,
            ..Options::default()
        };
        let sql = create_table(&orders(), Engine::Postgres, &opts);
        assert!(
            sql.starts_with("DROP TABLE IF EXISTS public.orders;\n"),
            "{sql}"
        );
        assert!(sql.contains("CREATE TABLE IF NOT EXISTS"), "{sql}");
    }

    #[test]
    fn a_table_with_no_key_has_no_primary_key_clause() {
        let t = TableSchema {
            name: "log".into(),
            columns: vec![col("line", "text", true)],
            ..Default::default()
        };
        let sql = create_table(&t, Engine::Sqlite, &Options::default());
        assert!(!sql.contains("PRIMARY KEY"), "{sql}");
    }

    #[test]
    fn the_script_groups_tables_then_indexes_then_keys() {
        let mut snap = Snapshot::new(Engine::Postgres, "PostgreSQL 16.4", "public");
        snap.tables = vec![orders()];
        let sql = script(&snap, Engine::Postgres, &Options::default());
        let create = sql.find("CREATE TABLE").unwrap();
        let index = sql.find("CREATE INDEX").unwrap();
        let alter = sql.find("ALTER TABLE").unwrap();
        assert!(create < index && index < alter, "{sql}");
        assert!(!sql.ends_with('\n'), "{sql}");
    }

    #[test]
    fn the_script_can_leave_indexes_and_keys_out() {
        let mut snap = Snapshot::new(Engine::Postgres, "PostgreSQL 16.4", "public");
        snap.tables = vec![orders()];
        let opts = Options {
            indexes: false,
            foreign_keys: false,
            ..Options::default()
        };
        let sql = script(&snap, Engine::Postgres, &opts);
        assert!(!sql.contains("CREATE INDEX"), "{sql}");
        assert!(!sql.contains("ALTER TABLE"), "{sql}");
    }
}
